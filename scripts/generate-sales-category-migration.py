#!/usr/bin/env python3
"""Generate the one-time legacy backfill from the same rules used by the POS parser."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docker/mysql/migrations/20261027-unify-sales-menu-categories.sql"
RULES = dict(line.split("=", 1) for line in
             (ROOT / "src/main/resources/sales/menu-category-rules.properties").read_text().splitlines()
             if line and not line.startswith("#"))


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def normalize(column):
    symbols = r"'[\\p{So}\\x{FE0F}\\x{200D}]'"
    base = f"REGEXP_REPLACE(COALESCE({column}, ''), {symbols}, '')"
    base = f"LOWER(TRIM(REGEXP_REPLACE({base}, '[[:space:]]+', ' ')))"
    return (f"REGEXP_REPLACE(REGEXP_REPLACE({base}, "
            "'non[ _-]*coffee|논커피|비커피', 'non'), '밀크티|milk[ ]*tea', 'tea')")


def resolve(prefix):
    return "CASE " + " ".join(f"WHEN {prefix}_{key} = 1 THEN {quote(key)}" for key in RULES) + " ELSE 'OTHER' END"


def generate():
    flags = ",\n       ".join(
        f"CASE WHEN REGEXP_LIKE({normalize(column)}, {quote(pattern)}) THEN 1 ELSE 0 END AS {prefix}_{key}"
        for prefix, column in [("raw", "category_raw"), ("menu", "menu_name")]
        for key, pattern in RULES.items())
    raw_count = " + ".join("raw_" + key for key in RULES)
    menu_count = " + ".join("menu_" + key for key in RULES)
    return f"""-- Generated by scripts/generate-sales-category-migration.py; do not edit by hand.
-- Stop uploads/readers/workers and back up sales_order_items before running.
-- Existing canonical categories (including an owner's OTHER choice) are preserved.
CREATE TEMPORARY TABLE sales_category_backfill AS
SELECT id,
       CASE
         WHEN standard_category IN ('NON_COFFEE','ADE','SMOOTHIE','BOTTLED_DRINK','BEER') THEN 'BEVERAGE'
         WHEN {raw_count} = 1 THEN {resolve('raw')}
         WHEN menu_CAKE + menu_BAKERY = 1 THEN CASE WHEN menu_CAKE = 1 THEN 'CAKE' ELSE 'BAKERY' END
         WHEN {menu_count} = 1 THEN {resolve('menu')}
         ELSE 'OTHER'
       END AS category
FROM (
  SELECT id, standard_category,
       {flags}
  FROM sales_order_items
  WHERE standard_category NOT IN ('COFFEE','TEA','BEVERAGE','CAKE','BAKERY','OTHER')
) classified;

ALTER TABLE sales_category_backfill ADD PRIMARY KEY (id);
START TRANSACTION;
UPDATE sales_order_items AS item
JOIN sales_category_backfill AS backfill ON backfill.id = item.id
SET item.standard_category = backfill.category;
COMMIT;
DROP TEMPORARY TABLE sales_category_backfill;

ALTER TABLE sales_order_items ADD CONSTRAINT ck_sales_item_standard_category CHECK
  (standard_category IN ('COFFEE','TEA','BEVERAGE','CAKE','BAKERY','OTHER'));
"""


if __name__ == "__main__":
    generated = generate()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != generated:
            raise SystemExit("Migration differs from parser rules; regenerate it.")
        print("Migration matches parser rules.")
    else:
        TARGET.write_text(generated)
